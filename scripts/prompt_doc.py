"""Write docs/learning-video-prompts.md: every prompt the learning-video path sends, verbatim.

    python -m scripts.prompt_doc

The prompt files in prompts/ are the source of truth. Run this after editing one, so the document
an auditor reads is the text the model is sent. No model calls.
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FENCE = "`" * 4


def _block(name: str) -> str:
    text = (ROOT / "prompts" / name).read_text(encoding="utf-8").rstrip("\n")
    return f"Source: `prompts/{name}` ({len(text):,} characters)\n\n{FENCE}text\n{text}\n{FENCE}\n"


def render() -> str:
    return f"""# Learning-video path: the prompts, verbatim

Generated by `python -m scripts.prompt_doc` from the files in `prompts/`. Do not edit by hand.
Companion to `docs/learning-video-system-flow.md`.

The path makes two kinds of model call. Each has a system prompt (a file in `prompts/`), a user
message built in code, and a repair message sent after a rejected answer. Both ask for JSON mode
and up to 4,096 output tokens. A lesson taught on a map makes only the first call: its visuals
are compiled by code (`planner/lesson_map.py`), so it has no visual prompt.

## 1. Lesson step

One call per video, up to three attempts. Code: `planner/lesson_plan.py` `generate`.

The recipe picked for the topic decides which one of these system prompts is sent (`board` in
`prompts/product_video_recipes.json`); the model is never sent both.

### System prompt, map lesson

{_block("lesson-plan-map.md")}
### System prompt, trace lesson (algorithms: code beside data)

{_block("lesson-plan-trace.md")}
### System prompt, any other lesson

{_block("lesson-plan-v2.md")}
### User message

Parts in braces are filled in. The length lines appear only when a duration or a scene limit is
given, and the icon list only for a map lesson.

{FENCE}text
Topic: {{topic}}

Selected skill: {{skill.id}}
Lesson guidance: {{skill.outline_guidance}}

Icon list: {{comma-separated icon names from assets/icons}}

Length: the narration (all spoken_text together) is about {{words}} words, between {{low}} and {{high}}.
Use at most {{max_scenes}} scene(s).

Return the lesson plan JSON now.
{FENCE}

`words` is the requested seconds times 2.8; `low` and `high` are 30% either side.

### Repair message

{FENCE}text
That was invalid ({{reason}}). Return only valid JSON.
{FENCE}

`reason` is one of: the schema error (including a move that does not fit the map); the
word-count or scene-count failure; the problems from `lesson_map_problems`; or, for a map
lesson, the validator's message from compiling and checking its scenes (`plan_map_scenes`).

## 2. Visual step, free route

One call per scene, up to three attempts. Used only when the lesson has no map.
Code: `planner/browser_visual_plan.py` `generate`.

### System prompt

{_block("browser-visual-plan-v2.md")}
### User message

{FENCE}text
Topic: {{topic}}
Selected skill: {{skill.id}}
Visual guidance: {{skill.scene_guidance}}
Scene {{n}} of {{total}}.
Audience: {{audience}}
Prerequisites: {{list}}
Whole lesson arc: {{id, goal, example and bridge of every scene, as JSON}}
Locked lesson scene:
{{the lesson scene as JSON}}

Pattern is a layout hint; choose the natural visual form.
Available local assets: {{icons and images, as JSON}}
Roles already used: {{roles}}
Previous pattern: {{pattern}}
Previous closing objects available for exact carryover:
{{objects, as JSON}}

Previous executed object state:
{{payloads after replay, as JSON}}

A reused id continues from that executed state. For a new method or fresh count, create a new pointer or counter id.

Choose visual forms from the claim requirements.
Return this one visual scene JSON now.
{FENCE}

### Repair message

{FENCE}text
This visual scene is invalid: {{reason}}. Repair only this scene. Make the locked visual anchors true in the executed object state; do not add a generic label box to claim a process happened. Keep prior object definitions and executed state, and use a new id for a new pointer or counter. Every claim needs its specified evidence from actual actions or values; for a message, request, or result card, prove a process by set_state on a drawn payload field (such as validated, status, or an argument value), not by highlight. Use only supported object kinds for the selected render_mode. Objects affected by move, compare, increment, set_state, or hold stay hidden unless they were opening-visible or explicitly appeared first. Return only corrected JSON.
{FENCE}

## 3. Not used by this path

`prompts/lesson-plan.md` and `prompts/browser-visual-plan.md` are the schema version 1 prompts,
kept for old saved projects. The other files in `prompts/` belong to the older Manim
code-generation pipeline.
"""


def main() -> int:
    target = ROOT / "docs" / "learning-video-prompts.md"
    target.write_text(render(), encoding="utf-8")
    print(f"wrote {target.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
